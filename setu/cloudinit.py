"""Build the cloud-init user-data that turns a fresh Ubuntu server into a Setu VPN."""
from __future__ import annotations

import base64
import json
import re
from typing import Any, Dict, Optional

REPO = "AnuragRoy485/setu"


def build(st: Dict[str, Any], ref: str = "main", harden: bool = True, ssh_key_given: bool = False) -> str:
    """Return a #!/bin/bash script. The state (with server private key) is embedded;
    the script deletes its own copy once the server is set up."""
    if not re.match(r"^[A-Za-z0-9._/-]+$", ref):
        raise ValueError("bad ref")
    payload = base64.b64encode(json.dumps(st).encode()).decode()
    lines = [
        "#!/bin/bash",
        "# Generated by Setu - installs a WireGuard VPN on first boot.",
        "set -euo pipefail",
        "export DEBIAN_FRONTEND=noninteractive",
        "exec > >(tee -a /var/log/setu-install.log) 2>&1",
        "apt-get update -y && apt-get install -y python3 curl ca-certificates",
        "mkdir -p /opt/setu /etc/setu && chmod 700 /etc/setu",
        "curl -fsSL https://github.com/%s/archive/%s.tar.gz | tar xz -C /opt/setu --strip-components=1" % (REPO, ref),
        "echo '%s' | base64 -d > /etc/setu/bootstrap.json && chmod 600 /etc/setu/bootstrap.json" % payload,
        "PYTHONPATH=/opt/setu python3 -m setu server init --state-file /etc/setu/bootstrap.json%s"
        % (" --harden" if harden else ""),
        "rm -f /etc/setu/bootstrap.json",
    ]
    if ssh_key_given:
        lines.append("sed -i 's/^#\\?PasswordAuthentication .*/PasswordAuthentication no/' /etc/ssh/sshd_config && systemctl reload ssh || true")
    lines += [
        "# the provider keeps a copy of user-data on disk; remove it (it holds the server key)",
        "rm -f /var/lib/cloud/instance/user-data.txt /var/lib/cloud/instance/scripts/* /var/lib/cloud/instances/*/user-data.txt* || true",
        "echo 'Setu is ready.'",
    ]
    return "\n".join(lines) + "\n"
